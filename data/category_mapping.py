def get_5big_category(item_code: str, item_version: str = None) -> str | None:
    """根据前6位编码获取5大类分类。

    Args:
        item_code: 清单项编码（9位或更长）
        item_version: 清单版本（2013/2024）

    Returns:
        5大类名称（电线电缆/管道/钢筋/水泥/混凝土），或 None（不做单价分析）
    """
    if not item_code or len(item_code) < 6:
        return None

    prefix6 = item_code[:6]

    # 根据版本选择前缀表
    if item_version == "2024":
        prefix_table = CODE_PREFIX_TO_CATEGORY_2024
    elif item_version == "2013":
        prefix_table = CODE_PREFIX_TO_CATEGORY_2013
    else:
        # 未知版本，两个表都查
        category = CODE_PREFIX_TO_CATEGORY_2024.get(prefix6)
        if not category:
            category = CODE_PREFIX_TO_CATEGORY_2013.get(prefix6)
        if not category:
            return None
        return CATEGORY_TO_5BIG.get(category)

    category = prefix_table.get(prefix6)
    if not category:
        return None

    return CATEGORY_TO_5BIG.get(category)

